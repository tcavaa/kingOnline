/**
 * Deterministic pick for a given room + round: every player computes the
 * same index (roomCode and round are shared state), so the sentence on the
 * table and on everyone's round-end modal is identical.
 */
export function quoteForRound(roomCode = '', round = 1) {
  let seed = round * 131
  const code = String(roomCode || '')
  for (let i = 0; i < code.length; i++) {
    seed = (seed * 33 + code.charCodeAt(i)) % 1000003
  }
  return QUOTES[Math.abs(seed) % QUOTES.length]
}
